import logging

from odoo.tools.translate import _
from odoo.tools import email_normalize
from odoo.exceptions import UserError

from odoo import api, fields, models, Command


_logger = logging.getLogger(__name__)


class CustomPortalWizard(models.TransientModel):
    _inherit = "portal.wizard"
    
    @api.depends('partner_ids')
    def _compute_user_ids(self):
        for portal_wizard in self:
            portal_wizard.user_ids = [
                Command.create({
                    'partner_id': partner.id,
                    'email': partner.university_email_address,
                })
                for partner in portal_wizard.partner_ids
            ]

    
    
class CustomPortalWizardUser(models.TransientModel):
    _inherit = "portal.wizard.user"
    
    def _create_user(self):
        return self.env['res.users'].with_context(no_reset_password=True)._create_user_from_template({
            'email': email_normalize(self.email),
            'login': email_normalize(self.email),
            'partner_id': self.partner_id.id,
            'company_id': self.env.company.id,
            'company_ids': [(6, 0, self.env.company.ids)],
        })
